    func testInfixPostfixAndTree() throws {
        let power = try InfixToPostfix.convert([
            .operatorToken(.neg), .numberLiteral("5"), .operatorToken(.pow), .numberLiteral("2")
        ])
        XCTAssertEqual(power.map(tokenText), ["5", "2", "^", "−"])
        let sine = try InfixToPostfix.convert([
            .numberLiteral("π"), .operatorToken(.div), .numberLiteral("2"), .operatorToken(.sin)
        ])
        XCTAssertEqual(sine.map(tokenText), ["π", "2", "÷", "sin"])
        let add = try InfixToPostfix.convert([
            .numberLiteral("9"), .operatorToken(.add), .numberLiteral("7"), .operatorToken(.mul), .numberLiteral("6")
        ])
        XCTAssertEqual(add.map(tokenText), ["9", "7", "6", "×", "+"])
        let right = try InfixToPostfix.convert([
            .numberLiteral("2"), .operatorToken(.pow), .numberLiteral("3"), .operatorToken(.pow), .numberLiteral("2")
        ])
        XCTAssertEqual(right.map(tokenText), ["2", "3", "2", "^", "^"])
        let grouped = try InfixToPostfix.convert([
            .leftParen, .numberLiteral("1"), .operatorToken(.add), .numberLiteral("2"), .rightParen, .operatorToken(.mul), .numberLiteral("3")
        ])
        XCTAssertEqual(grouped.map(tokenText), ["1", "2", "+", "3", "×"])
        let unary = try InfixToPostfix.convert([.numberLiteral("9"), .operatorToken(.sqrt)])
        XCTAssertEqual(unary.map(tokenText), ["9", "√"])
        let logic = try InfixToPostfix.convert([
            .numberLiteral("1"), .operatorToken(.or), .numberLiteral("2"), .operatorToken(.and), .numberLiteral("3")
        ])
        XCTAssertEqual(logic.map(tokenText), ["1", "2", "3", "and", "or"])
        XCTAssertEqual(try InfixToPostfix.convert([]), [])
        assertKind(.unbalancedParentheses) {
            _ = try InfixToPostfix.convert([.numberLiteral("1"), .rightParen])
        }
        assertKind(.unbalancedParentheses) {
            _ = try InfixToPostfix.convert([.leftParen, .numberLiteral("1")])
        }
        let tree = try ExpressionTreeBuilder.build(add, base: .decimal)
        guard case .binary(.add, let left, let rightNode) = tree else {
            XCTFail("shape")
            return
        }
        XCTAssertEqual(left.raw, "9")
        guard case .binary(.mul, let seven, let six) = rightNode else {
            XCTFail("mul")
            return
        }
        XCTAssertEqual(seven.raw, "7")
        XCTAssertEqual(six.raw, "6")
        XCTAssertEqual(try tree.evaluate(), 51)
        XCTAssertEqual(tree.displayLabel(base: .decimal), "+ = 51")
        XCTAssertEqual(tree.childCount, 2)
        XCTAssertNil(tree.childAt(2))
        let powered = try ExpressionTreeBuilder.build(right, base: .decimal)
        XCTAssertEqual(try powered.evaluate(), 512)
        let sqrt = try ExpressionTreeBuilder.build([.numberLiteral("9"), .operatorToken(.sqrt)], base: .decimal)
        XCTAssertEqual(try sqrt.evaluate(), 3)
        XCTAssertEqual(sqrt.displayLabel(base: .decimal), "√ = 3")
        let value = ExpressionNode.value(8, "8")
        XCTAssertEqual(try value.evaluate(), 8)
        XCTAssertEqual(value.childCount, 0)
        XCTAssertNil(value.operatorKind)
        XCTAssertEqual(value.displayLabel(base: .decimal), "8")
        let hex = try ExpressionTreeBuilder.build([.numberLiteral("A")], base: .hexadecimal)
        XCTAssertEqual(try hex.evaluate(), 10)
