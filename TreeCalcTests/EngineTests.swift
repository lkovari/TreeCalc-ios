    func testPlaybackSteps() {
        var playback = PostfixPlayback()
        playback.toggle(count: 4, stepByStep: false)
        XCTAssertEqual(playback.index, 0)
        XCTAssertTrue(playback.running)
        playback.tick(count: 4)
        XCTAssertEqual(playback.index, 1)
        playback.toggle(count: 4, stepByStep: false)
        XCTAssertEqual(playback.index, 1)
        XCTAssertFalse(playback.running)
        playback.toggle(count: 4, stepByStep: false)
        XCTAssertEqual(playback.index, 1)
        XCTAssertTrue(playback.running)
        playback.tick(count: 4)
        XCTAssertEqual(playback.index, 2)
        var finished = PostfixPlayback(index: 2, running: false)
        finished.toggle(count: 3, stepByStep: false)
        XCTAssertEqual(finished.index, 0)
        XCTAssertTrue(finished.running)
        finished.select(1)
        XCTAssertEqual(finished.index, 1)
        XCTAssertFalse(finished.running)
        finished.select(1)
        XCTAssertNil(finished.index)
        var stepped = PostfixPlayback()
        stepped.step(count: 3)
        XCTAssertEqual(stepped.index, 0)
        XCTAssertFalse(stepped.running)
        stepped.step(count: 3)
        XCTAssertEqual(stepped.index, 1)
        stepped = PostfixPlayback(index: 2, running: true)
        stepped.step(count: 3)
        XCTAssertEqual(stepped.index, 2)
        XCTAssertFalse(stepped.running)
        stepped.step(count: 0)
        XCTAssertEqual(stepped.index, 2)
        stepped.stop()
        XCTAssertNil(stepped.index)
        XCTAssertFalse(stepped.running)
    }

    private func show(_ expression: String) -> String {
        let engine = fresh()
        pressAll(engine, expression)
        engine.press(.equals)
        return engine.snapshot().display
    }

    private func fresh() -> CalculatorEngine {
        CalculatorEngine()
    }
}

func pressAll(_ engine: CalculatorEngine, _ expression: String) {
    for character in expression {
        switch character {
        case "0": engine.press(.digit0)
        case "1": engine.press(.digit1)
        case "2": engine.press(.digit2)
        case "3": engine.press(.digit3)
        case "4": engine.press(.digit4)
        case "5": engine.press(.digit5)
        case "6": engine.press(.digit6)
        case "7": engine.press(.digit7)
        case "8": engine.press(.digit8)
        case "9": engine.press(.digit9)
        case "A", "a": engine.press(.digitA)
        case "B", "b": engine.press(.digitB)
        case "C", "c": engine.press(.digitC)
        case "D", "d": engine.press(.digitD)
        case "E", "e": engine.press(.digitE)
        case "F", "f": engine.press(.digitF)
        case "+": engine.press(.add)
        case "-": engine.press(.sub)
        case "*": engine.press(.mul)
        case "/": engine.press(.div)
        case "(": engine.press(.leftParen)
        case ")": engine.press(.rightParen)
        case ".": engine.press(.dot)
        case "^": engine.press(.pow)
        default: break
        }
    }
}

func tokenText(_ token: Token) -> String {
    switch token {
    case .numberLiteral(let raw): raw
    case .operatorToken(let kind): kind.displaySymbol
    case .leftParen: "("
    case .rightParen: ")"
    }
}

func assertKind(_ kind: ErrorKind, _ body: () throws -> Void, file: StaticString = #filePath, line: UInt = #line) {
    do {
        try body()
        XCTFail("expected \(kind)", file: file, line: line)
    } catch let error as CalculatorException {
        XCTAssertEqual(error.kind, kind, file: file, line: line)
    } catch {
        XCTFail("unexpected \(error)", file: file, line: line)
    }
}
